"""Aggregate run results into a Markdown leaderboard."""

from __future__ import annotations

import json
from collections import defaultdict
from datetime import date
from pathlib import Path
from typing import Any


def _load_runs(run_paths: list[Path]) -> list[dict]:
    """Load all run JSON files. Each file may contain a list of records or a single record."""
    records: list[dict] = []
    for p in run_paths:
        text = p.read_text(encoding="utf-8").strip()
        if not text:
            continue
        data = json.loads(text)
        if isinstance(data, list):
            records.extend(data)
        elif isinstance(data, dict):
            records.append(data)
    return records


def _fmt_pct(num: int, denom: int) -> str:
    if denom == 0:
        return "0/0 (—)"
    pct = round(100 * num / denom)
    return f"{num}/{denom} ({pct}%)"


def _fmt_latency(ms_values: list[float]) -> str:
    if not ms_values:
        return "—"
    mean = sum(ms_values) / len(ms_values)
    return f"{mean / 1000:.1f}s"


def render_leaderboard(run_paths: list[Path], task_ids: list[str] | None = None) -> str:
    """Render a Markdown leaderboard from a list of run JSON file paths.

    Each record in the JSON files must have the shape:
      {
        "model": str,
        "task_id": str,
        "passed": bool,
        "plan_pass": bool,
        "answer_pass": bool,
        "latency_ms": float,
        "error": str | None,
      }
    """
    records = _load_runs([p for p in run_paths if p.exists()])

    if not records:
        return _placeholder()

    # Group by model
    # model → {task_id → list[record]}
    by_model: dict[str, dict[str, list[dict]]] = defaultdict(lambda: defaultdict(list))
    for rec in records:
        by_model[rec["model"]][rec["task_id"]].append(rec)

    # Collect all task_ids seen
    all_task_ids: list[str] = task_ids or sorted(
        {rec["task_id"] for rec in records}
    )

    today = date.today().isoformat()
    task_count = len(all_task_ids)

    lines: list[str] = [
        "# GeoChatBot Evaluation Leaderboard",
        "",
        f"> Run on {today} against `packages/eval/tasks/nyc_311_v1.json` ({task_count} tasks).",
        "",
        "| Model | Pass rate | Plan-shape pass | Answer pass | Mean latency | Notes |",
        "|---|---|---|---|---|---|",
    ]

    model_rows: list[tuple[str, int, str]] = []  # (model, pass_count, row)

    for model, task_map in sorted(by_model.items()):
        total_tasks = task_count
        pass_count = 0
        plan_pass_count = 0
        answer_pass_count = 0
        latencies: list[float] = []
        notes: list[str] = []

        for tid in all_task_ids:
            task_records = task_map.get(tid, [])
            if not task_records:
                continue
            # Take the latest record per task
            rec = task_records[-1]
            if rec.get("passed"):
                pass_count += 1
            if rec.get("plan_pass"):
                plan_pass_count += 1
            if rec.get("answer_pass"):
                answer_pass_count += 1
            if rec.get("latency_ms"):
                latencies.append(float(rec["latency_ms"]))
            if rec.get("error"):
                # Shorten error
                err = str(rec["error"])[:60]
                notes.append(f"{tid}: {err}")

        covered = sum(1 for tid in all_task_ids if task_map.get(tid))
        note_str = "; ".join(notes[:2]) or "—"

        row = (
            f"| {model} "
            f"| {_fmt_pct(pass_count, covered)} "
            f"| {_fmt_pct(plan_pass_count, covered)} "
            f"| {_fmt_pct(answer_pass_count, covered)} "
            f"| {_fmt_latency(latencies)} "
            f"| {note_str} |"
        )
        model_rows.append((model, pass_count, row))

    # Sort by pass count descending
    model_rows.sort(key=lambda x: x[1], reverse=True)
    for _, _, row in model_rows:
        lines.append(row)

    # Per-task breakdown
    lines += [
        "",
        "## Per-task breakdown",
        "",
    ]

    model_names = [m for m, _, _ in model_rows]
    header = "| Task | " + " | ".join(model_names) + " |"
    sep = "|---|" + "|".join(["---"] * len(model_names)) + "|"
    lines.append(header)
    lines.append(sep)

    for tid in all_task_ids:
        cells: list[str] = [f"`{tid}`"]
        for model in model_names:
            task_records = by_model[model].get(tid, [])
            if not task_records:
                cells.append("—")
            else:
                rec = task_records[-1]
                cells.append("OK" if rec.get("passed") else "FAIL")
        lines.append("| " + " | ".join(cells) + " |")

    lines.append("")
    lines.append("---")
    lines.append("*Generated by `python -m geochatbot_eval leaderboard`*")
    lines.append("")

    return "\n".join(lines)


def _placeholder() -> str:
    today = date.today().isoformat()
    return f"""# GeoChatBot Evaluation Leaderboard

> No runs yet — see `packages/eval/README.md` to run.

| Model | Pass rate | Plan-shape pass | Answer pass | Mean latency | Notes |
|---|---|---|---|---|---|
| *(no data)* | — | — | — | — | Run the harness to populate this table. |

## How to generate this table

```bash
cd packages/eval
python -m geochatbot_eval run \\
  --site http://localhost:5173/app \\
  --tasks tasks/nyc_311_v1.json \\
  --models claude-sonnet-4-6,claude-haiku-4-5-20251001 \\
  --api-key $ANTHROPIC_API_KEY \\
  --out runs/run-$(date +%Y%m%d-%H%M%S).json

python -m geochatbot_eval leaderboard \\
  --runs runs/*.json \\
  --out ../../EVALS.md
```

---
*Last updated: {today}*
"""
